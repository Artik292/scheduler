CREATE TABLE IF NOT EXISTS counter (
    id INT UNSIGNED NOT NULL PRIMARY KEY,
    counter BIGINT NOT NULL DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS subject (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    name VARCHAR(255) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS teacher (
    id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    surname VARCHAR(255) NOT NULL,
    class VARCHAR(150) DEFAULT NULL,
    cabinet VARCHAR(50) NOT NULL,
    subject_id INT UNSIGNED NOT NULL,
    available TINYINT(1) NOT NULL DEFAULT 1,
    start_time VARCHAR(5) NOT NULL DEFAULT '17:00',
    end_time VARCHAR(5) NOT NULL DEFAULT '19:00',
    CONSTRAINT fk_teacher_subject FOREIGN KEY (subject_id) REFERENCES subject(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS text (
    id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    code VARCHAR(255) NOT NULL,
    text TEXT NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS vecaki (
    id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    student_name VARCHAR(255) NOT NULL,
    grade VARCHAR(255) NOT NULL,
    parent_name VARCHAR(255) NOT NULL,
    contact_phone VARCHAR(255) NOT NULL,
    time VARCHAR(5) NOT NULL,
    teacher_id INT UNSIGNED NOT NULL,
    CONSTRAINT fk_booking_teacher FOREIGN KEY (teacher_id) REFERENCES teacher(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS sessions (
    sess_id VARBINARY(128) NOT NULL PRIMARY KEY,
    sess_data BLOB NOT NULL,
    sess_lifetime INT UNSIGNED NOT NULL,
    sess_time INT UNSIGNED NOT NULL,
    INDEX sessions_expiry (sess_time)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS rate_limits (
    rate_key CHAR(64) CHARACTER SET ascii NOT NULL PRIMARY KEY,
    attempts INT UNSIGNED NOT NULL,
    reset_at BIGINT UNSIGNED NOT NULL,
    INDEX rate_limits_expiry (reset_at)
) ENGINE=InnoDB;
